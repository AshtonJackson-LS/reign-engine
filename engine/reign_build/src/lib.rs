//! Build-script helper for Reign projects.
//!
//! A project's `build.rs` is one line:
//!
//! ```ignore
//! fn main() {
//!     reign_build::components();
//! }
//! ```
//!
//! and its `src/lib.rs` includes what it writes:
//!
//! ```ignore
//! include!(concat!(env!("OUT_DIR"), "/reign_components.rs"));
//! ```
//!
//! Every `.rs` file in `src/components/` becomes a module of `components`.
//! Each `#[derive(... Component ...)]` type in them is registered with the
//! editor, and each type with an `impl Behaviour<World> for Type` runs its
//! callbacks in Play. Adding a component is adding a file: nothing to list
//! by hand.
//!
//! This crate has no dependencies, so it builds in a moment. It also holds
//! the tooling Reign Hub and the editor share: setting a project up for code
//! ([`project`]) and opening it in a code editor ([`ide`]).

pub mod ide;
pub mod project;
pub mod release;

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// What one source file declares.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Scan {
    /// Types with `Component` in their derive list.
    pub components: Vec<String>,
    /// Types with an `impl Behaviour<...> for Type`.
    pub behaviours: Vec<String>,
}

/// Generates `$OUT_DIR/reign_components.rs` from `src/components/`.
pub fn components() {
    let manifest =
        PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("run from build.rs"));
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("run from build.rs"));
    let dir = manifest.join("src").join("components");
    println!("cargo:rerun-if-changed={}", dir.display());
    let code = generate(&dir, |path| {
        println!("cargo:rerun-if-changed={}", path.display());
    });
    std::fs::write(out.join("reign_components.rs"), code).expect("write reign_components.rs");
}

/// The generated module and `scripts()` for the files in `dir`. `seen` is
/// told about each file read.
pub fn generate(dir: &Path, mut seen: impl FnMut(&Path)) -> String {
    let mut files: Vec<PathBuf> = std::fs::read_dir(dir)
        .map(|d| {
            d.filter_map(|e| e.ok().map(|e| e.path()))
                .filter(|p| p.extension().is_some_and(|x| x == "rs"))
                .collect()
        })
        .unwrap_or_default();
    files.sort();

    let mut modules = String::new();
    let mut register = String::new();
    let mut behaviours = String::new();
    for path in &files {
        seen(path);
        let Some(module) = path.file_stem().and_then(|s| s.to_str()).filter(|s| is_ident(s)) else {
            println!(
                "cargo:warning={} is skipped: file names in src/components must be snake_case Rust names",
                path.display()
            );
            continue;
        };
        if module == "mod" {
            continue;
        }
        let source = std::fs::read_to_string(path).unwrap_or_default();
        let scan = scan(&source);
        let _ = writeln!(
            modules,
            "    #[path = {:?}]\n    pub mod {module};",
            path.display().to_string()
        );
        for ty in &scan.components {
            let _ = writeln!(register, "            r.register::<components::{module}::{ty}>();");
        }
        for ty in &scan.behaviours {
            let _ =
                writeln!(behaviours, "            b.behaviour::<components::{module}::{ty}>();");
        }
    }

    let closure = |arg: &str, body: &str| {
        if body.is_empty() { "|_| {}".to_owned() } else { format!("|{arg}| {{\n{body}        }}") }
    };
    format!(
        "// Generated by reign_build from src/components/. Don't edit: add or change files there.\n\
         \n\
         /// Your components: one module per file in `src/components/`.\n\
         pub mod components {{\n{modules}}}\n\
         \n\
         /// Your project's code, for the Reign editor.\n\
         pub fn scripts() -> ::reign_engine::Scripts {{\n\
         \x20   ::reign_engine::Scripts {{\n\
         \x20       project: Some(env!(\"CARGO_PKG_NAME\")),\n\
         \x20       register: {},\n\
         \x20       behaviours: {},\n\
         \x20   }}\n\
         }}\n",
        closure("r", &register),
        closure("b", &behaviours),
    )
}

/// Finds component types and Behaviour impls in one file's source.
pub fn scan(source: &str) -> Scan {
    let code = strip_comments(source);
    let mut scan = Scan::default();

    // Components: a derive list naming `Component`, then the next type.
    let mut rest = code.as_str();
    while let Some(at) = rest.find("#[derive(") {
        rest = &rest[at + "#[derive(".len()..];
        let Some(end) = rest.find(")]") else { break };
        let derives = &rest[..end];
        let is_component =
            derives.split(',').any(|d| d.trim().rsplit("::").next() == Some("Component"));
        rest = &rest[end..];
        if !is_component {
            continue;
        }
        if let Some(name) = next_type_name(rest) {
            scan.components.push(name);
        }
    }

    // Behaviours: `impl ...Behaviour<...> for Name`.
    let mut rest = code.as_str();
    while let Some(at) = rest.find("Behaviour<") {
        let before = &rest[..at];
        rest = &rest[at + "Behaviour<".len()..];
        // `impl Behaviour<..>` or `impl some::path::Behaviour<..>`.
        let mut words = before.split_whitespace().rev();
        let is_impl = match words.next() {
            Some("impl") => true,
            Some(path) if path.ends_with("::") => words.next() == Some("impl"),
            _ => false,
        };
        // Skip to the matching '>'.
        let mut depth = 1;
        let mut end = None;
        for (i, c) in rest.char_indices() {
            match c {
                '<' => depth += 1,
                '>' => {
                    depth -= 1;
                    if depth == 0 {
                        end = Some(i);
                        break;
                    }
                }
                _ => {}
            }
        }
        let Some(end) = end else { break };
        rest = &rest[end + 1..];
        if !is_impl {
            continue;
        }
        let after = rest.trim_start();
        if let Some(name) = after.strip_prefix("for").filter(|a| a.starts_with(char::is_whitespace))
        {
            let name: String = name
                .trim_start()
                .chars()
                .take_while(|c| c.is_alphanumeric() || *c == '_')
                .collect();
            if !name.is_empty() && !scan.behaviours.contains(&name) {
                scan.behaviours.push(name);
            }
        }
    }
    scan
}

/// The name in the next `struct Name` or `enum Name`, skipping other
/// attributes and visibility.
fn next_type_name(code: &str) -> Option<String> {
    let mut words =
        code.split(|c: char| c.is_whitespace() || c == '{' || c == '(' || c == ';' || c == '<');
    while let Some(word) = words.next() {
        match word {
            "struct" | "enum" => {
                let name = words.find(|w| !w.is_empty())?;
                return is_ident(name).then(|| name.to_owned());
            }
            "fn" | "impl" | "mod" | "trait" | "type" | "const" | "static" | "use" => return None,
            _ => {}
        }
    }
    None
}

fn strip_comments(source: &str) -> String {
    let mut out = String::with_capacity(source.len());
    let mut chars = source.chars().peekable();
    while let Some(c) = chars.next() {
        match (c, chars.peek()) {
            ('/', Some('/')) => {
                for c in chars.by_ref() {
                    if c == '\n' {
                        out.push('\n');
                        break;
                    }
                }
            }
            ('/', Some('*')) => {
                chars.next();
                let mut last = ' ';
                for c in chars.by_ref() {
                    if last == '*' && c == '/' {
                        break;
                    }
                    last = c;
                }
                out.push(' ');
            }
            ('"', _) => {
                // Skip string contents, so text in strings never matches.
                out.push('"');
                let mut escaped = false;
                for c in chars.by_ref() {
                    if escaped {
                        escaped = false;
                    } else if c == '\\' {
                        escaped = true;
                    } else if c == '"' {
                        break;
                    }
                }
                out.push('"');
            }
            _ => out.push(c),
        }
    }
    out
}

fn is_ident(s: &str) -> bool {
    let mut chars = s.chars();
    chars.next().is_some_and(|c| c.is_alphabetic() || c == '_')
        && chars.all(|c| c.is_alphanumeric() || c == '_')
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_components_and_behaviours() {
        let source = r#"
            use reign_engine::prelude::*;

            /// Moves with the arrow keys.
            #[derive(Clone, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize, Component)]
            #[serde(default)]
            pub struct PlayerController {
                pub speed: Fx,
            }

            impl Behaviour<World> for PlayerController {
                fn fixed_update(ctx: &mut Ctx, me: ObjectId) {}
            }

            #[derive(Clone, Debug)]
            struct NotAComponent;

            #[derive(Clone, Default, PartialEq, Eq, Hash, Serialize, Deserialize, reign::scene::Component)]
            enum Team { #[default] Red, Blue }

            // impl Behaviour<World> for Commented {}
            const S: &str = "impl Behaviour<World> for InAString";
        "#;
        let scan = scan(source);
        assert_eq!(scan.components, ["PlayerController", "Team"]);
        assert_eq!(scan.behaviours, ["PlayerController"]);
    }

    #[test]
    fn generates_modules_and_registration() {
        let dir = std::env::temp_dir().join(format!("reign-build-test-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(
            dir.join("spinner.rs"),
            "#[derive(Component)] pub struct Spinner { pub speed: i32 }\nimpl Behaviour<World> for Spinner {}",
        )
        .unwrap();
        std::fs::write(dir.join("Bad Name.rs"), "").unwrap();
        let code = generate(&dir, |_| {});
        assert!(code.contains("pub mod spinner;"));
        assert!(code.contains("r.register::<components::spinner::Spinner>();"));
        assert!(code.contains("b.behaviour::<components::spinner::Spinner>();"));
        assert!(!code.contains("Bad Name"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn no_components_still_generates() {
        let code = generate(Path::new("/definitely/not/here"), |_| {});
        assert!(code.contains("register: |_| {}"));
    }
}
