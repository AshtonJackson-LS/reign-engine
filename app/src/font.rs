/// The font asset that describes [`atlas`].
pub fn asset() -> Font {
    Font {
        texture: Handle::new(FONT_TEXTURE),
        cell: CELL,
        columns: COLUMNS,
        first: FIRST,
        last: LAST,
        space: CELL[0],
    }
}

/// The glyphs as a white-on-clear RGBA image: its width, height and pixels.
pub fn atlas() -> (u32, u32, Vec<u8>) {
    let rows = (GLYPHS.len() as u32).div_ceil(COLUMNS);
    let (width, height) = (COLUMNS * CELL[0], rows * CELL[1]);
    let mut rgba = vec![0u8; (width * height * 4) as usize];
    for (i, glyph) in GLYPHS.iter().enumerate() {
        let (cx, cy) = (i as u32 % COLUMNS * CELL[0], i as u32 / COLUMNS * CELL[1]);
        for (y, bits) in glyph.iter().enumerate() {
            for x in 0..5 {
                if bits & (0x10 >> x) != 0 {
                    let at = (((cy + y as u32) * width + cx + x) * 4) as usize;
                    rgba[at..at + 4].copy_from_slice(&[255, 255, 255, 255]);
                }
            }
        }
    }
    (width, height, rgba)
}

/// Where a character is in a font's texture (x, y, w, h in texels), or
/// `None` if the font doesn't have it.
pub fn glyph_rect(font: &Font, c: char) -> Option<[u32; 4]> {
    let code = u32::from(c);
    if code < u32::from(font.first) || code > u32::from(font.last) || font.columns == 0 {
        return None;
    }
    let index = code - u32::from(font.first);
    let [w, h] = font.cell;
    Some([index % font.columns * w, index / font.columns * h, w, h])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_character_has_ink_except_space() {
        assert_eq!(GLYPHS.len(), (LAST - FIRST) as usize + 1);
        for (i, glyph) in GLYPHS.iter().enumerate() {
            let c = (FIRST + i as u8) as char;
            assert_eq!(glyph.iter().any(|row| *row != 0), c != ' ', "{c:?}");
            assert!(glyph.iter().all(|row| *row < 0x20), "{c:?} fits in five pixels");
        }
        // Letters are all different from one another.
        let mut seen: Vec<&[u8; 7]> = GLYPHS.iter().collect();
        seen.sort();
        seen.dedup();
        assert_eq!(seen.len(), GLYPHS.len(), "two characters look the same");
    }

    #[test]
    fn glyphs_sit_in_their_cells() {
        let font = asset();
        assert_eq!(glyph_rect(&font, ' '), Some([0, 0, 6, 8]));
        assert_eq!(glyph_rect(&font, 'A'), Some([6, 16, 6, 8]));
        assert_eq!(glyph_rect(&font, '~'), Some([84, 40, 6, 8]));
        assert_eq!(glyph_rect(&font, '\u{e9}'), None);
        let (w, h, rgba) = atlas();
        assert_eq!((w, h), (96, 48));
        // 'A' starts with ".###.": clear, then ink.
        let alpha = |x: u32, y: u32| rgba[((y * w + x) * 4 + 3) as usize];
        assert_eq!((alpha(6, 16), alpha(7, 16), alpha(11, 16)), (0, 255, 0));
    }
}
