//! The built-in font: a 5 by 7 pixel face covering printable ASCII, drawn
//! here so every project has text without shipping a font file. It's white
//! with hard edges, so it tints cleanly and scales by whole pixels.

use reign::assets::{Font, Guid, Handle};

pub const FONT_TEXTURE: Guid = Guid(0x5245_4947_4e00_0046_4f4e_5400_0000_0001);
pub const FONT: Guid = Guid(0x5245_4947_4e00_0046_4f4e_5400_0000_0002);

/// A glyph's cell in the atlas: 5 by 7 of ink plus a pixel of spacing.
pub const CELL: [u32; 2] = [6, 8];
const COLUMNS: u32 = 16;
const FIRST: u8 = b' ';
const LAST: u8 = b'~';

/// The built-in font's handle: what a new Text starts with.
pub fn font() -> Handle<Font> {
    Handle::new(FONT)
}

